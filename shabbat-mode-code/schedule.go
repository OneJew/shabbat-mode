func findCity(name string) City {
	for _, c := range cities {
		if c.Name == name {
			return c
		}
	}
	for _, c := range cities {
		if c.Name == "ירושלים" {
			return c
		}
	}
	return cities[0]
}

type Entry struct {
	Name    string    `json:"name"`
	Date    string    `json:"date"`
	Sunset  time.Time `json:"sunset"`
	Candle  time.Time `json:"candle"`
	Action  time.Time `json:"action"`
	Skipped bool      `json:"skipped"`
}

// entriesFrom lists the next count entries whose candle lighting has not passed.
func entriesFrom(now time.Time, cfg Config, count int) []Entry {
	city := findCity(cfg.City)
	local := now.Location()
	var out []Entry
	for i := 0; i < 400 && len(out) < count; i++ {
		day := time.Date(now.Year(), now.Month(), now.Day()+i, 12, 0, 0, 0, time.UTC)
		rd := rataDie(day.Year(), day.Month(), day.Day())
		name, ok := entryFor(rd)
		if !ok || (!cfg.Holidays && name != "ערב שבת") {
			continue
		}
		sunset := sunsetUTC(day.Year(), day.Month(), day.Day(), city.Lat, city.Lon).In(local)
		candle := sunset.Add(-time.Duration(cfg.CandleMinutes) * time.Minute)
		if !candle.After(now) {
			continue
		}
		date := day.Format("2006-01-02")
		out = append(out, Entry{
			Name: name, Date: date, Sunset: sunset, Candle: candle,
			Action:  candle.Add(-time.Duration(cfg.LeadMinutes) * time.Minute),
			Skipped: cfg.SkipDate == date,
		})
	}
	return out
}
